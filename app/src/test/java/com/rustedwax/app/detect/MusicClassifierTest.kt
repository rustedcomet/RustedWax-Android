	// region hashtag-only titles

	@Test
	fun `a title of nothing but hashtags is not a song`() {
		assertEquals(
			video,
			kindOf(
				"#guitar #dubstep #djdubstep #fnaf #fivenightsatfreddy",
				"katter",
				durationMs = 30_000L,
				category = "Music",
			),
		)
		assertEquals(
			video,
			kindOf("#plena#panama 🇵🇦", "Rony González", durationMs = 52_000L, category = "Music"),
		)
	}

	@Test
	fun `hashtag-only outranks the category but not real provenance`() {
		// A distributor feed's title is catalogue metadata and never looks like
		// this, so provenance still wins if it somehow does.
		assertEquals(
			song,
			kindOf("#guitar #dubstep", "Some Artist - Topic", category = "Music"),
		)
		assertEquals(
			song,
			kindOf("#guitar #dubstep", "Some Artist", category = "Music", autoGenerated = true),
		)
	}

	/** A real title with tags appended keeps its kind — only the tags go. */
	@Test
	fun `tags appended to a real title do not change the kind`() {
		assertEquals(
