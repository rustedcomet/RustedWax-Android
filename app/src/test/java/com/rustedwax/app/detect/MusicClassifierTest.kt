		)
		assertEquals(
			song,
			kindOf("Radiohead - Live at Glastonbury", "Some Channel",
				durationMs = 90 * 60 * 1000L),
		)
	}

	/** An ordinary-length video is untouched by either gate. */
	@Test
	fun `the middle of the range is unaffected`() {
		assertEquals(song, kindOf("Korn - Trash", "Some Channel", durationMs = 4 * 60 * 1000L))
	}
