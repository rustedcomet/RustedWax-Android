	// rule and became a song.

	@Test
	fun `a long podcast with a dash in the title is not a song`() {
		assertEquals(
			video,
			kindOf("Lex Fridman - Conversation with Someone", "Some Channel",
				durationMs = 45 * 60 * 1000L),
		)
	}

	@Test
	fun `a medium-form clip needs a positive music signal`() {
		assertEquals(
			video,
			kindOf("Jimmy Fallon - Interviewing A Guest", "Late Night",
				durationMs = 10 * 60 * 1000L),
		)
	}

	/** Real long-form music always carries a signal, and those are checked first. */
	@Test
	fun `long-form music with a real signal still passes`() {
		assertEquals(
			song,
			kindOf("Some Artist - Greatest Hits (Full Album)", "Some Channel",
				durationMs = 50 * 60 * 1000L),
		)
		assertEquals(
			song,
			kindOf("DJ Someone - Summer Set", "Some Channel",
